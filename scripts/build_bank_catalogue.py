"""Generate offline catalogue artifacts from the single reviewed Python source."""
import argparse
import json
import sys
from pathlib import Path

root=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(root/'backend'))
from app.services.bank_catalogue_data import catalogue,ratio


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    payload=catalogue()
    assert len({b['code'] for b in payload['banks']})==len(payload['banks'])
    for bank in payload['banks']:
        for mode in ('light','dark'):
            colors=bank[mode]
            assert all(ratio(colors[fg],colors[bg])>=4.5 for fg in ('primary','error','text_primary','text_secondary') for bg in ('background','surface','card'))
            assert ratio(colors['button_background'],colors['button_text'])>=4.5
    value=json.dumps(payload,ensure_ascii=False,indent=2)+'\n'
    outputs={root/'frontend/faisal_app/assets/data/bank_catalogue.json':value,
             root/'frontend/faisal_app/lib/features/banks/domain/entities/bank_catalogue.g.dart':
             "// GENERATED by scripts/build_bank_catalogue.py. Do not edit.\nconst bankCatalogueJson = r'''"+value+"''';\n"}
    for path,text in outputs.items():
        if args.check:
            assert path.read_text(encoding='utf-8')==text,f'Out-of-date catalogue: {path.name}'
        else:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_text(text,encoding='utf-8')
    print(f'Validated {len(payload["banks"])} bank presets; generated artefacts '+('match.' if args.check else 'written.'))


if __name__=='__main__':
    main()
